/* Human-readable names for the gas UI. Raw GPX labels stay internal. */
window.gasPointLabel=function(point,km){
  const canonical=window.TRAVERSEE_GAS_POINTS.find(p=>p.id===point?.id);
  if(canonical?.name&&!/^GAZ\b/i.test(canonical.name))return canonical.name;
  if(point?.name&&!/^GAZ\b/i.test(point.name))return point.name;
  const note=String(point?.note||'').replace(/\s+/g,' ').trim();
  const alias=note.match(/Autre nom\s*:\s*(?:km[\d.,]+\s*)?([^|]+)/i);
  let label=alias?.[1]?.trim().replace(/[.,;:]$/,'')||'';
  if(!label||/^GAZ\b/i.test(label)){
    const match=note.match(/\b(Bricomarché|Decathlon|Intersport|Mr\.?\s*Bricolage|Sport\s*2000|Weldom|Intermarché|Carrefour|Super\s*U|Hyper\s*U|E\.Leclerc|Leroy\s*Merlin|Castorama|Tardieu)\b/i);
    label=match?.[1]?.trim()||'';
  }
  label=label.replace(/\bkm[\d.,]+\s*/i,'').trim();
  const cityMatch=note.match(/\b\d{5}\s+([^.|]+?)(?=\.|\||$)/);
  const city=point?.city||canonical?.city||cityMatch?.[1]?.trim().replace(/[.,;:]$/,'')||'';
  if(label&&city&&!label.toLowerCase().includes(city.toLowerCase()))return label+' · '+city;
  if(label)return label;
  const fallback=Number.isFinite(Number(km))?Number(km):Number(String(point?.name||'').match(/[\d.,]+/)?.[0]?.replace(',','.'));
  return 'Point de ravitaillement · km '+(Number.isFinite(fallback)?fallback.toFixed(1).replace('.',','):'—');
};
